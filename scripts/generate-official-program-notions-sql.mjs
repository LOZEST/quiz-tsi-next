import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const programPath = resolve(root, 'src/data/program/official-program-v2.json');
const outputPath = process.argv[2]
  ? resolve(process.cwd(), process.argv[2])
  : null;

const program = JSON.parse(await readFile(programPath, 'utf8'));
const chaptersById = new Map(
  program.chapters.map((chapter) => [chapter.id, chapter]),
);

const escape = (value) => value.replace(/'/g, "''");

const rows = program.notions
  .map((notion) => {
    const chapter = chaptersById.get(notion.chapterId);
    if (!chapter) {
      throw new Error(
        `Notion "${notion.id}" references unknown chapter "${notion.chapterId}"`,
      );
    }
    return {
      notionId: notion.id,
      chapterId: notion.chapterId,
      partId: chapter.partId,
      chapterLabel: chapter.label,
      notionLabel: notion.label,
    };
  })
  .sort((a, b) => a.notionId.localeCompare(b.notionId));

const values = rows
  .map(
    (row) =>
      `  ('${escape(row.notionId)}','${escape(row.chapterId)}','${escape(row.partId)}','${escape(row.chapterLabel)}','${escape(row.notionLabel)}')`,
  )
  .join(',\n');

const sql = `-- Generated by scripts/generate-official-program-notions-sql.mjs
-- Source: src/data/program/official-program-v2.json (${rows.length} notions)
-- Do not edit by hand: re-run the script and paste the output into a new migration.
delete from public.official_program_notions;
insert into public.official_program_notions (notion_id, chapter_id, part_id, chapter_label, notion_label) values
${values};
`;

if (outputPath) {
  await writeFile(outputPath, sql);
} else {
  process.stdout.write(sql);
}

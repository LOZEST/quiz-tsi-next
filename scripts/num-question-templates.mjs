export function buildNumPrompt(calculId) {
  const template = PROMPT_TEMPLATES[calculId];
  if (!template) throw new Error(`Gabarit d’énoncé absent pour ${calculId}.`);
  return template.map((value, index) =>
    index % 2 === 0 ? text(value) : math(value),
  );
}

export function listNumPromptTemplateIds() {
  return Object.keys(PROMPT_TEMPLATES);
}
